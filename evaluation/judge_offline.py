"""Reference-aware judge: does the answer recover what the reference says?

llm-zoomcamp 04-evaluation/lessons/13-llm-as-judge.md's A->Q->A' setup, where
the judge sees the original answer as well as the generated one. That is the
difference from monitoring/judge.py, which scores live traffic and has no
reference to compare against.

The labels are deliberately not RelevanceVerdict's. Relevance and correctness
are different questions — an answer can be squarely on topic and wrong — and
sharing the model would make two incomparable numbers look comparable.

  uv run python -m evaluation.judge_offline
"""

import argparse
import csv
import logging
import time
from collections import Counter
from typing import Literal, NamedTuple

from pydantic import BaseModel

from evaluation import DATA_DIR, DEFAULT_MODEL
from evaluation.answers import RUNS_PATH, load_runs
from monitoring.llm import llm_structured_retry
from monitoring.metrics import calculate_cost

logger = logging.getLogger(__name__)

VERDICTS_PATH = DATA_DIR / "answer-verdicts.csv"
METRICS_PATH = DATA_DIR / "answer-metrics.csv"

# Recorded rather than dropped: a variant must not score better because the
# judge happened to fail on its hardest answers.
MISSING_VERDICT = "MISSING"

LABELS = ("CORRECT", "PARTLY_CORRECT", "INCORRECT", MISSING_VERDICT)


class AnswerVerdict(BaseModel):
    verdict: Literal["CORRECT", "PARTLY_CORRECT", "INCORRECT"]
    explanation: str


class ScoredAnswer(NamedTuple):
    verdict: str
    explanation: str
    cost: float


JUDGE_INSTRUCTIONS = """
You are an expert evaluator for a question-answering system about the 2022 FIFA
World Cup in Qatar. You will be given:

1. A question.
2. A reference answer, which is correct.
3. An answer generated by the system.

Decide whether the generated answer recovers the information in the reference
answer.

Classify as:
- CORRECT: the generated answer conveys the same key information as the
  reference. It does not need to match word for word, and extra correct detail
  is fine. Every part of a multi-part question must be covered.
- PARTLY_CORRECT: it gets some of the reference right and some wrong or
  missing — typically one clause of a multi-part question answered and the
  other dropped, or the right entity with the wrong number.
- INCORRECT: it contradicts the reference, misses its key point entirely, or
  says it does not know when the reference contains a real answer.

If the reference says the system should decline to answer, then declining IS
CORRECT, and producing a confident answer instead is INCORRECT. These are the
off-topic questions, where refusing is the behaviour we want.

Judge only against the reference, not against your own World Cup knowledge, and
focus on correctness rather than style or length.
""".strip()

JUDGE_PROMPT = """
Question:
{question}

Reference answer:
{reference}

Generated answer:
{answer}
""".strip()


def judge_answer(
    question, reference, answer, client=None, model=DEFAULT_MODEL, sleep=time.sleep
) -> ScoredAnswer:
    """Score one answer against its reference. Raises if the judge is unreachable."""
    if client is None:
        from openai import OpenAI

        client = OpenAI()

    prompt = JUDGE_PROMPT.format(
        question=question, reference=reference, answer=answer or "(no answer)"
    )
    result, usage = llm_structured_retry(
        client,
        JUDGE_INSTRUCTIONS,
        prompt,
        AnswerVerdict,
        model=model,
        sleep=sleep,
    )
    return ScoredAnswer(result.verdict, result.explanation, calculate_cost(model, usage))


def judge_or_missing(
    question, reference, answer, client=None, model=DEFAULT_MODEL, sleep=time.sleep
) -> ScoredAnswer:
    """judge_answer, but a broken judge yields MISSING rather than an exception."""
    try:
        return judge_answer(
            question, reference, answer, client=client, model=model, sleep=sleep
        )
    except Exception:
        logger.warning("judge failed for %r; recording MISSING", question, exc_info=True)
        return ScoredAnswer(MISSING_VERDICT, "judge unavailable", 0.0)


def summarise(rows) -> list[dict]:
    """One row per variant: verdict counts, correct share, and what it cost."""
    by_variant: dict[str, list] = {}
    for row in rows:
        by_variant.setdefault(row["variant"], []).append(row)

    summary = []
    for variant, variant_rows in sorted(by_variant.items()):
        counts = Counter(row["verdict"] for row in variant_rows)
        answers = len(variant_rows)
        summary.append(
            {
                "variant": variant,
                "answers": answers,
                **{label: counts.get(label, 0) for label in LABELS},
                # MISSING sits in the denominator: an unscored answer is not
                # evidence of a correct one.
                "correct_share": counts.get("CORRECT", 0) / answers,
                "routed_as_expected": sum(
                    row["actual_path"] == row["expected_path"] for row in variant_rows
                ),
                "mean_cost": sum(float(row["cost"]) for row in variant_rows) / answers,
                "mean_tokens": sum(int(row["total_tokens"]) for row in variant_rows)
                / answers,
                "mean_latency": sum(float(row["response_time"]) for row in variant_rows)
                / answers,
            }
        )
    return summary


def judge_runs(runs, references, client=None, model=DEFAULT_MODEL, sleep=time.sleep):
    """Attach a verdict to every run. References are keyed by question id."""
    judged = []
    for run in runs:
        scored = judge_or_missing(
            run["question"],
            references[run["id"]],
            run["answer"],
            client=client,
            model=model,
            sleep=sleep,
        )
        judged.append(
            run
            | {
                "verdict": scored.verdict,
                "explanation": scored.explanation,
                "judge_cost": scored.cost,
            }
        )
    return judged


def write_csv(rows, path, fieldnames=None) -> None:
    if not rows:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames or list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def main() -> None:
    from dotenv import load_dotenv
    from openai import OpenAI

    from evaluation.answers import load_questions

    logging.basicConfig(level=logging.INFO)
    load_dotenv()

    parser = argparse.ArgumentParser(description="Judge the variant runs.")
    parser.add_argument("--model", default=DEFAULT_MODEL)
    args = parser.parse_args()

    runs = load_runs(RUNS_PATH)
    references = {row["id"]: row["reference"] for row in load_questions()}
    print(f"judging {len(runs)} runs")

    judged = judge_runs(runs, references, OpenAI(), args.model)
    write_csv(judged, VERDICTS_PATH)

    summary = summarise(judged)
    write_csv(summary, METRICS_PATH)
    for row in summary:
        print(
            f"{row['variant']:<8} correct {row['correct_share']:.1%}  "
            f"({row['CORRECT']}/{row['answers']})  "
            f"missing {row[MISSING_VERDICT]}  "
            f"${row['mean_cost']:.5f}/answer"
        )
    print(f"\n-> {VERDICTS_PATH}\n-> {METRICS_PATH}")


if __name__ == "__main__":
    main()
